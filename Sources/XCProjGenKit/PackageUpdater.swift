import Foundation

public enum PackageUpdater {
    public static func update(in directory: URL, to version: String, using tool: PklTool) throws
        -> String
    {
        let versionPattern = /(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)/
        guard version.wholeMatch(of: versionPattern) != nil else {
            throw ProjectError("Expected a stable X.Y.Z version, got '\(version)'")
        }

        let manifest = directory.appendingPathComponent("PklProject")
        let lockfile = directory.appendingPathComponent("PklProject.deps.json")
        guard let original = try readFile(manifest) else {
            throw ProjectError("PklProject not found at \(manifest.path)")
        }
        let uri = ToolDefaults.packageURI(for: version)
        let unsupported = ProjectError(
            "Cannot update the xcproj dependency in \(manifest.path). Set its uri to \(uri) and run pkl project resolve."
        )
        guard let source = String(data: original, encoding: .utf8),
            let literal = dependencyLiteral(in: source)
        else { throw unsupported }

        let oldURI = String(literal.text.dropFirst().dropLast())
        guard let oldVersion = oldURI.split(separator: "@").last.map(String.init),
            oldVersion.wholeMatch(of: versionPattern) != nil,
            oldURI == ToolDefaults.packageURI(for: oldVersion)
        else { throw unsupported }

        let installation = try tool.installation()
        guard installation.isSupported else {
            throw ProjectError("Pkl \(PklTool.minimumVersion) or later is required.")
        }
        func effectiveURI() throws -> String {
            let data = try tool.evaluate(manifest, expression: #"dependencies["xcproj"].uri"#)
            return String(decoding: data, as: UTF8.self).trimmingCharacters(in: .newlines)
        }
        guard try effectiveURI() == oldURI else { throw unsupported }

        let originalLock = try readFile(lockfile)
        let updated = Data(source.replacingCharacters(in: literal.range, with: "\"\(uri)\"").utf8)
        let manifestChanged = updated != original
        if manifestChanged { try updated.write(to: manifest, options: .atomic) }

        let lockChanged: Bool
        do {
            if manifestChanged, try effectiveURI() != uri { throw unsupported }
            try tool.resolveProject(at: directory)
            lockChanged = try readFile(lockfile) != originalLock
        } catch {
            var diagnostics = [error.localizedDescription]
            for (file, data) in [(manifest, Optional(original)), (lockfile, originalLock)] {
                do {
                    guard try readFile(file) != data else { continue }
                    if let data {
                        try data.write(to: file, options: .atomic)
                    } else {
                        try FileManager.default.removeItem(at: file)
                    }
                } catch {
                    diagnostics.append(
                        "Could not restore \(file.path): \(error.localizedDescription)")
                }
            }
            throw ProjectError(diagnostics)
        }

        if !manifestChanged && !lockChanged { return "xcproj is already up to date (\(version))." }
        let files = [
            manifestChanged ? manifest.lastPathComponent : nil,
            lockChanged ? lockfile.lastPathComponent : nil,
        ].compactMap { $0 }.joined(separator: ", ")
        let change = manifestChanged ? "\(oldVersion) → \(version)" : version
        return "Updated xcproj (\(change)): \(files)"
    }

    private static func readFile(_ url: URL) throws -> Data? {
        do {
            let attributes = try FileManager.default.attributesOfItem(atPath: url.path)
            guard attributes[.type] as? FileAttributeType == .typeRegular else {
                throw ProjectError("Expected a regular file: \(url.path)")
            }
            return try Data(contentsOf: url)
        } catch let error as CocoaError
            where error.code == .fileReadNoSuchFile || error.code == .fileNoSuchFile
        {
            return nil
        }
    }

    private struct Token {
        let text: Substring
        let range: Range<String.Index>
    }

    // Recognize the literal dependency block generated by init. Tokenize comments
    // and strings together so embedded copies of the block are never edited.
    private static func dependencyLiteral(in source: String) -> Token? {
        let pattern =
            #"\s+|//[^\r\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\\r\n])*"|[A-Za-z_][A-Za-z_0-9]*|[^\s]"#
        guard let regex = try? NSRegularExpression(pattern: pattern) else { return nil }
        let tokens: [Token] = regex.matches(
            in: source, range: NSRange(source.startIndex..., in: source)
        )
        .compactMap { match in
            guard let range = Range(match.range, in: source) else { return nil }
            let text = source[range]
            if text.first?.isWhitespace == true || text.hasPrefix("//") { return nil }
            if text.hasPrefix("/*"), !text.dropFirst(2).contains("/*") { return nil }
            return Token(text: text, range: range)
        }

        // Complex strings and nested block comments are outside this editor's grammar.
        guard
            !tokens.contains(where: {
                $0.text == "#" || $0.text == "\"" || $0.text.hasPrefix("/*")
                    || $0.text.contains(#"\("#)
            }), !source.contains(#""""#)
        else { return nil }

        var depth = 0
        var dependenciesDepth: Int?
        var literal: Token?
        for index in tokens.indices {
            let text = tokens[index].text
            if depth == 0, text == "dependencies", tokens.dropFirst(index + 1).first?.text == "{" {
                guard dependenciesDepth == nil, literal == nil else { return nil }
                dependenciesDepth = 1
            }
            if depth == dependenciesDepth, text == "[",
                tokens.dropFirst(index + 1).first?.text == #""xcproj""#
            {
                let entry = tokens.dropFirst(index).prefix(8).map(\.text)
                guard literal == nil, entry.count == 8,
                    Array(entry.prefix(6)) == ["[", #""xcproj""#, "]", "{", "uri", "="],
                    entry[7] == "}"
                        || (entry[7] == ";" && tokens.dropFirst(index + 8).first?.text == "}")
                else { return nil }
                literal = tokens[index + 6]
            }
            switch text {
            case "{", "[", "(": depth += 1
            case "}", "]", ")":
                depth -= 1
                if depth == 0 { dependenciesDepth = nil }
            default: break
            }
        }
        return depth == 0 ? literal : nil
    }
}
